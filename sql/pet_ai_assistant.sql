SET NAMES utf8mb4;

-- ------------------------------------------------------------
-- ① 知识库：AI 可回答的范围由这张表决定，不写死在提示词里
--    category: health 健康 / care 养护 / policy 政策 / faq 常见问题
--    emergency=1 表示红旗症状，命中后必须先建议就医，不给家庭处理方案
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `pet_knowledge` (
  `knowledge_id` BIGINT       NOT NULL AUTO_INCREMENT COMMENT '知识ID',
  `title`        VARCHAR(120) NOT NULL                COMMENT '标题',
  `category`     VARCHAR(32)  NOT NULL DEFAULT 'care' COMMENT '分类（health/care/policy/faq）',
  `species`      VARCHAR(32)  DEFAULT '通用'          COMMENT '适用科系（猫科/犬科/通用…）',
  `keywords`     VARCHAR(255) DEFAULT ''              COMMENT '检索关键词（逗号分隔）',
  `question`     VARCHAR(255) DEFAULT ''              COMMENT '典型问法',
  `content`      TEXT         NOT NULL                COMMENT '知识正文（纯文本，保留换行）',
  `severity`     VARCHAR(16)  DEFAULT 'low'           COMMENT '严重程度（low/medium/high）',
  `emergency`    CHAR(1)      DEFAULT '0'             COMMENT '是否红旗急症（0否 1是）',
  `source`       VARCHAR(64)  DEFAULT '运营维护'      COMMENT '来源',
  `sort`         INT          DEFAULT 0               COMMENT '排序',
  `hit_count`    INT          DEFAULT 0               COMMENT '命中次数',
  `status`       CHAR(1)      DEFAULT '0'             COMMENT '状态（0启用 1停用）',
  `del_flag`     CHAR(1)      DEFAULT '0'             COMMENT '删除标志',
  `create_by`    VARCHAR(64)  DEFAULT '',
  `create_time`  DATETIME     DEFAULT NULL,
  `update_by`    VARCHAR(64)  DEFAULT '',
  `update_time`  DATETIME     DEFAULT NULL,
  PRIMARY KEY (`knowledge_id`),
  UNIQUE KEY `uk_knowledge_title` (`title`),
  KEY `idx_knowledge_cat` (`category`, `status`),
  FULLTEXT KEY `ft_knowledge` (`title`, `question`, `keywords`, `content`) WITH PARSER ngram
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI 知识库';

-- ------------------------------------------------------------
-- ② 会话：一个页面场景一次会话，便于客服接管与效果复盘
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `pet_ai_conversation` (
  `conv_id`     BIGINT       NOT NULL AUTO_INCREMENT COMMENT '会话ID',
  `conv_no`     VARCHAR(32)  NOT NULL                COMMENT '会话号',
  `user_id`     BIGINT       DEFAULT NULL            COMMENT '用户ID（游客为空）',
  `user_name`   VARCHAR(64)  DEFAULT ''              COMMENT '用户账号',
  `scene`       VARCHAR(32)  DEFAULT 'shop'          COMMENT '场景（home/detail/match/order/consult/admin_consult）',
  `biz_id`      VARCHAR(64)  DEFAULT ''              COMMENT '业务ID（petId/orderNo/consultId）',
  `title`       VARCHAR(120) DEFAULT ''              COMMENT '会话标题（取首问）',
  `store_id`    BIGINT       DEFAULT NULL            COMMENT '归属门店',
  `message_count` INT        DEFAULT 0               COMMENT '消息条数',
  `last_time`   DATETIME     DEFAULT NULL            COMMENT '最后消息时间',
  `status`      CHAR(1)      DEFAULT '0'             COMMENT '状态（0进行中 1已转人工 2已结束）',
  `create_time` DATETIME     DEFAULT NULL,
  `update_time` DATETIME     DEFAULT NULL,
  PRIMARY KEY (`conv_id`),
  UNIQUE KEY `uk_conv_no` (`conv_no`),
  KEY `idx_conv_user` (`user_id`, `create_time`),
  KEY `idx_conv_scene` (`scene`, `create_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI 会话';

CREATE TABLE IF NOT EXISTS `pet_ai_message` (
  `msg_id`       BIGINT     NOT NULL AUTO_INCREMENT COMMENT '消息ID',
  `conv_id`      BIGINT     NOT NULL                COMMENT '会话ID',
  `role`         VARCHAR(16) NOT NULL               COMMENT '角色（user/assistant/system）',
  `content`      TEXT       NOT NULL                COMMENT '回答正文',
  `blocks_json`  LONGTEXT   DEFAULT NULL            COMMENT '业务卡片 JSON（宠物/商品/订单/预约）',
  `citations_json` TEXT     DEFAULT NULL            COMMENT '引用来源 JSON',
  `actions_json` VARCHAR(2000) DEFAULT NULL         COMMENT '建议动作 JSON',
  `tool_names`   VARCHAR(255) DEFAULT ''            COMMENT '本次调用工具',
  `latency_ms`   INT        DEFAULT NULL            COMMENT '耗时（毫秒）',
  `create_time`  DATETIME   DEFAULT NULL,
  PRIMARY KEY (`msg_id`),
  KEY `idx_msg_conv` (`conv_id`, `msg_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI 会话消息';

CREATE TABLE IF NOT EXISTS `pet_ai_feedback` (
  `feedback_id` BIGINT     NOT NULL AUTO_INCREMENT COMMENT '反馈ID',
  `conv_id`     BIGINT     DEFAULT NULL            COMMENT '会话ID',
  `msg_id`      BIGINT     DEFAULT NULL            COMMENT '消息ID',
  `user_id`     BIGINT     DEFAULT NULL            COMMENT '用户ID',
  `rating`      CHAR(1)    NOT NULL                COMMENT '评价（1有用 0无用）',
  `reason`      VARCHAR(255) DEFAULT ''            COMMENT '原因',
  `create_time` DATETIME   DEFAULT NULL,
  PRIMARY KEY (`feedback_id`),
  KEY `idx_feedback_msg` (`msg_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI 回答反馈';

